// Builds the golden-vector document from the scenarios. Shared by scripts/golden.ts and the tests.

import {
  HIGH_PROTEIN_CONFIG,
  STANDARD_CONFIG,
  mealBudget,
  rankChain,
  rankMealDeal,
  resolveSlots,
  type RankResult,
} from "../src/ranking.ts";
import {
  budgetCases,
  chainCases,
  configs,
  mealDealCases,
  menuOrder,
  planCases,
  runChainCase,
  runMealDealCase,
  slotCases,
} from "./scenarios.ts";
import {
  syntheticBudget,
  syntheticChain,
  syntheticChainBudgets,
  syntheticChainSpec,
  syntheticDealBudgets,
  syntheticDealSpec,
  syntheticMealDeal,
  syntheticProteinG,
} from "./synthetic.ts";

function summarise(result: RankResult) {
  return {
    nothingFits: result.nothingFits,
    evaluated: result.evaluated,
    orders: result.orders.map((order) => ({
      key: order.key,
      itemIds: order.itemIds,
      swapIds: order.swapIds,
      kcal: order.kcal,
      proteinG: order.proteinG,
      score: order.score,
      fits: order.fits,
      overByKcal: order.overByKcal,
      swapSavingKcal: order.swapSavingKcal,
      ...(order.premium !== undefined ? { premium: order.premium } : {}),
    })),
  };
}

/** Full-size cases on the synthetic menus, so the Swift search is checked at the sizes it must be fast at. */
function syntheticCases() {
  const chain = syntheticChain(syntheticChainSpec);
  const { retailer, deal } = syntheticMealDeal(syntheticDealSpec);
  return {
    chainSpec: syntheticChainSpec,
    dealSpec: syntheticDealSpec,
    proteinG: syntheticProteinG,
    chains: syntheticChainBudgets.map((kcal) => {
      const budget = syntheticBudget(kcal, syntheticProteinG);
      const result = rankChain(chain, { budget, serving: "lunch", dietTags: [], favourites: [], config: STANDARD_CONFIG });
      return { budgetKcal: kcal, budget, expected: summarise(result) };
    }),
    mealDeals: syntheticDealBudgets.map((kcal) => {
      const budget = syntheticBudget(kcal, syntheticProteinG);
      const result = rankMealDeal(deal, retailer, {
        budget,
        serving: "lunch",
        dietTags: [],
        favourites: [],
        includePremium: true,
        config: STANDARD_CONFIG,
      });
      return { budgetKcal: kcal, budget, expected: summarise(result) };
    }),
  };
}

export function goldenDocument() {
  return {
    formulaVersion: 1,
    note: "Generated by scripts/golden.ts in scran-data from examples/. Scores compare to 1e-9; order and keys must match exactly.",
    configs: { standard: STANDARD_CONFIG, highProtein: HIGH_PROTEIN_CONFIG },
    slots: slotCases.map((c) => ({ ...c, expected: resolveSlots(c.state) })),
    budgets: budgetCases.map((c) => ({ ...c, expected: mealBudget(c.input, configs[c.config]) })),
    chains: chainCases.map((c) => ({ ...c, expected: summarise(runChainCase(c)) })),
    mealDeals: mealDealCases.map((c) => ({ ...c, expected: summarise(runMealDealCase(c)) })),
    menus: ["bakehouse-and-co", "the-red-lion"].map((chain) => ({ chain, expected: menuOrder(chain) })),
    plans: planCases(),
    synthetic: syntheticCases(),
  };
}

export function goldenText(): string {
  return JSON.stringify(goldenDocument(), null, 2) + "\n";
}
